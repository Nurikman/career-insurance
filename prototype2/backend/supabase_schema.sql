-- tirek database schema for Supabase (Postgres).
-- Run once: Supabase dashboard → SQL Editor → New query → paste this file → Run.
-- Safe to re-run (IF NOT EXISTS). Times are Unix seconds (bigint), report/state data is JSON text.
--
-- Security: Row Level Security is ON for every table and there are NO policies,
-- so the public "publishable/anon" key can read or write nothing.
-- Only the backend, using the SECRET key (service role), can access these tables.

create table if not exists users (
  id text primary key,
  email text unique not null,
  name text not null,
  surname text not null,
  country text not null,
  pw_salt text not null,
  pw_hash text not null,
  created_at bigint not null,
  last_login_at bigint,
  terms_accepted_at bigint not null,
  consent_version text not null,
  consent_store_cv smallint not null default 0,
  consent_research smallint not null default 0
);

create table if not exists sessions (
  token_hash text primary key,
  user_id text not null references users(id) on delete cascade,
  expires_at bigint not null
);

create table if not exists consent_log (
  id bigint generated by default as identity primary key,
  user_id text not null references users(id) on delete cascade,
  created_at bigint not null,
  kind text not null,
  value smallint not null,
  version text not null
);

create table if not exists profiles (
  user_id text primary key references users(id) on delete cascade,
  role_current text, target_role text, target_salary text, study_hours text,
  about text, cv_text text, cv_name text, cv_saved_at bigint,   -- only with consent_store_cv = 1
  updated_at bigint not null
);

create table if not exists state (
  user_id text primary key references users(id) on delete cascade,
  data text not null,
  updated_at bigint not null
);

create table if not exists reports (
  id bigint generated by default as identity primary key,
  user_id text not null references users(id) on delete cascade,
  created_at bigint not null,
  data text not null
);

create table if not exists feedback (
  id bigint generated by default as identity primary key,
  user_id text references users(id) on delete set null,
  created_at bigint not null,
  rating smallint, buy_pro text, comment text
);

create table if not exists events (
  id bigint generated by default as identity primary key,
  user_id text references users(id) on delete set null,
  created_at bigint not null,
  name text not null
);

create table if not exists admin_audit (
  id bigint generated by default as identity primary key,
  created_at bigint not null,
  ip text, action text not null, target text
);

create index if not exists ix_reports_user on reports(user_id, created_at);
create index if not exists ix_events_name on events(name);
create index if not exists ix_sessions_user on sessions(user_id);

alter table users enable row level security;
alter table sessions enable row level security;
alter table consent_log enable row level security;
alter table profiles enable row level security;
alter table state enable row level security;
alter table reports enable row level security;
alter table feedback enable row level security;
alter table events enable row level security;
alter table admin_audit enable row level security;
